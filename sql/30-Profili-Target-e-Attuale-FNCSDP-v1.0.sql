CREATE OR REPLACE FUNCTION public.fn_approva_profilo_target_fncsdp(p_profilo_target_id bigint)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
    v_controlli integer;
    v_senza_mapping integer;
BEGIN
    IF NOT public.fn_accesso_operativo() THEN
        RAISE EXCEPTION 'Accesso operativo non autorizzato.';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM public.profilo_target_fncsdp
        WHERE id = p_profilo_target_id
          AND attiva IS TRUE
          AND stato = 'BOZZA'
    ) THEN
        RAISE EXCEPTION 'Profilo Target non disponibile oppure gia approvato.';
    END IF;

    SELECT count(*)
    INTO v_controlli
    FROM public.controllo_target_fncsdp
    WHERE profilo_target_id = p_profilo_target_id
      AND attiva IS TRUE;

    IF v_controlli = 0 THEN
        RAISE EXCEPTION 'Il Profilo Target non contiene controlli attivi.';
    END IF;

    SELECT count(*)
    INTO v_senza_mapping
    FROM public.controllo_target_fncsdp c
    WHERE c.profilo_target_id = p_profilo_target_id
      AND c.attiva IS TRUE
      AND NOT EXISTS (
          SELECT 1
          FROM public.controllo_target_subcategory_fncsdp m
          WHERE m.controllo_target_id = c.id
            AND m.attiva IS TRUE
      );

    IF v_senza_mapping > 0 THEN
        RAISE EXCEPTION '% controlli non possiedono una Subcategory associata.', v_senza_mapping;
    END IF;

    PERFORM set_config('app.fncsdp_target_approval', '1', true);

    UPDATE public.profilo_target_fncsdp
    SET
        stato = 'APPROVATO',
        approvato_da = auth.uid(),
        approvato_il = clock_timestamp(),
        aggiornato_il = clock_timestamp()
    WHERE id = p_profilo_target_id;

    RETURN p_profilo_target_id;
END;
$$;

