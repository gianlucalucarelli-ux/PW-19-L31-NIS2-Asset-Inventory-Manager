CREATE VIEW public.vista_profili_target_fncsdp
WITH (security_invoker = true)
AS
SELECT
    pt.id AS profilo_target_id,
    pt.organizzazione_id,
    o.codice_organizzazione,
    o.nome AS organizzazione_nome,
    pt.codice,
    pt.nome,
    pt.descrizione,
    pt.perimetro,
    pt.versione,
    pt.stato,
    pt.approvato_il,
    pt.approvato_da,
    pt.attiva,
    pt.creato_il,
    pt.aggiornato_il,
    count(DISTINCT c.id) FILTER (WHERE c.attiva IS TRUE) AS numero_controlli,
    count(DISTINCT m.subcategory_id) FILTER (WHERE m.attiva IS TRUE AND c.attiva IS TRUE) AS numero_subcategory,
    count(DISTINCT a.id) FILTER (WHERE a.attiva IS TRUE) AS numero_assessment,
    max(a.data_assessment) FILTER (WHERE a.attiva IS TRUE) AS ultimo_assessment_il
FROM public.profilo_target_fncsdp pt
JOIN public.organizzazione o ON o.id = pt.organizzazione_id
LEFT JOIN public.controllo_target_fncsdp c ON c.profilo_target_id = pt.id
LEFT JOIN public.controllo_target_subcategory_fncsdp m ON m.controllo_target_id = c.id
LEFT JOIN public.assessment_fncsdp a ON a.profilo_target_id = pt.id
GROUP BY
    pt.id,
    o.codice_organizzazione,
    o.nome;

CREATE VIEW public.vista_controlli_target_fncsdp
WITH (security_invoker = true)
AS
SELECT
    c.id AS controllo_target_id,
    c.profilo_target_id,
    pt.organizzazione_id,
    pt.codice AS profilo_codice,
    pt.nome AS profilo_nome,
    pt.stato AS profilo_stato,
    c.codice,
    c.nome,
    c.descrizione,
    c.copertura_target,
    c.ordine,
    c.attiva,
    s.id AS subcategory_id,
    s.versione_framework,
    s.codice AS subcategory_codice,
    split_part(s.codice, '.', 1) AS funzione_codice,
    split_part(s.codice, '-', 1) AS categoria_codice,
    s.descrizione AS subcategory_descrizione,
    m.peso,
    m.id AS mapping_id
FROM public.controllo_target_fncsdp c
JOIN public.profilo_target_fncsdp pt ON pt.id = c.profilo_target_id
JOIN public.controllo_target_subcategory_fncsdp m
  ON m.controllo_target_id = c.id
 AND m.attiva IS TRUE
JOIN public.fncsdp_subcategory s
  ON s.id = m.subcategory_id
 AND s.attiva IS TRUE;

CREATE VIEW public.vista_profili_attuali_fncsdp
WITH (security_invoker = true)
AS
WITH metriche AS (
    SELECT
        a.id AS assessment_id,
        count(DISTINCT c.id) FILTER (WHERE c.attiva IS TRUE) AS numero_controlli,
        count(DISTINCT mc.id) FILTER (
            WHERE mc.attiva IS TRUE
              AND mc.copertura_attuale IS NOT NULL
        ) AS controlli_misurati,
        count(DISTINCT mc.id) FILTER (
            WHERE mc.attiva IS TRUE
              AND mc.copertura_attuale > 0
              AND mc.livello_maturita IS NOT NULL
        ) AS controlli_con_maturita,
        CASE
            WHEN sum(m.peso) FILTER (WHERE c.attiva IS TRUE AND m.attiva IS TRUE AND c.copertura_target > 0) > 0
            THEN round(
                sum(
                    least(1.00, coalesce(mc.copertura_attuale, 0.00) / nullif(c.copertura_target, 0.00)) * m.peso
                ) FILTER (WHERE c.attiva IS TRUE AND m.attiva IS TRUE AND c.copertura_target > 0)
                /
                sum(m.peso) FILTER (WHERE c.attiva IS TRUE AND m.attiva IS TRUE AND c.copertura_target > 0),
                4
            )
            ELSE NULL
        END AS score,
        CASE
            WHEN sum(m.peso) FILTER (
                WHERE c.attiva IS TRUE
                  AND m.attiva IS TRUE
                  AND mc.copertura_attuale > 0
                  AND mc.livello_maturita IS NOT NULL
            ) > 0
            THEN round(
                sum(mc.livello_maturita * m.peso) FILTER (
                    WHERE c.attiva IS TRUE
                      AND m.attiva IS TRUE
                      AND mc.copertura_attuale > 0
                      AND mc.livello_maturita IS NOT NULL
                )
                /
                sum(m.peso) FILTER (
                    WHERE c.attiva IS TRUE
                      AND m.attiva IS TRUE
                      AND mc.copertura_attuale > 0
                      AND mc.livello_maturita IS NOT NULL
                ),
                2
            )
            ELSE NULL
        END AS maturita_media_indicativa
    FROM public.assessment_fncsdp a
    JOIN public.controllo_target_fncsdp c ON c.profilo_target_id = a.profilo_target_id
    JOIN public.controllo_target_subcategory_fncsdp m ON m.controllo_target_id = c.id
    LEFT JOIN public.misura_controllo_fncsdp mc
      ON mc.assessment_id = a.id
     AND mc.controllo_target_id = c.id
     AND mc.attiva IS TRUE
    GROUP BY a.id
)
SELECT
    a.id AS assessment_id,
    a.profilo_target_id,
    pt.organizzazione_id,
    o.codice_organizzazione,
    o.nome AS organizzazione_nome,
    pt.codice AS profilo_target_codice,
    pt.nome AS profilo_target_nome,
    a.codice,
    a.nome,
    a.data_assessment,
    a.responsabile_assessor_id,
    concat_ws(' ', r.nome, r.cognome) AS assessor_nome,
    r.email AS assessor_email,
    a.note,
    a.stato,
    a.completato_il,
    a.completato_da,
    a.attiva,
    a.creato_il,
    a.aggiornato_il,
    mt.numero_controlli,
    mt.controlli_misurati,
    CASE
        WHEN mt.numero_controlli > 0
        THEN round(mt.controlli_misurati::numeric / mt.numero_controlli::numeric, 4)
        ELSE 0.0000
    END AS avanzamento,
    mt.score,
    CASE WHEN mt.score IS NULL THEN NULL ELSE round(1.0000 - mt.score, 4) END AS gap,
    mt.maturita_media_indicativa
FROM public.assessment_fncsdp a
JOIN public.profilo_target_fncsdp pt ON pt.id = a.profilo_target_id
JOIN public.organizzazione o ON o.id = pt.organizzazione_id
LEFT JOIN public.responsabile r ON r.id = a.responsabile_assessor_id
LEFT JOIN metriche mt ON mt.assessment_id = a.id;

CREATE VIEW public.vista_valutazione_fncsdp
WITH (security_invoker = true)
AS
SELECT
    a.id AS assessment_id,
    a.codice AS assessment_codice,
    a.nome AS assessment_nome,
    a.stato AS assessment_stato,
    a.data_assessment,
    pt.id AS profilo_target_id,
    pt.codice AS profilo_target_codice,
    pt.nome AS profilo_target_nome,
    pt.organizzazione_id,
    o.codice_organizzazione,
    o.nome AS organizzazione_nome,
    c.id AS controllo_target_id,
    c.codice AS controllo_codice,
    c.nome AS controllo_nome,
    c.descrizione AS controllo_descrizione,
    c.copertura_target,
    c.ordine,
    s.id AS subcategory_id,
    s.codice AS subcategory_codice,
    split_part(s.codice, '.', 1) AS funzione_codice,
    split_part(s.codice, '-', 1) AS categoria_codice,
    s.descrizione AS subcategory_descrizione,
    m.peso,
    mc.id AS misura_id,
    mc.risposta,
    mc.note_copertura,
    mc.copertura_attuale,
    mc.note_maturita,
    mc.livello_maturita,
    mc.evidenze,
    mc.note,
    CASE
        WHEN c.copertura_target > 0 AND mc.copertura_attuale IS NOT NULL
        THEN round(least(1.00, mc.copertura_attuale / c.copertura_target), 4)
        ELSE NULL
    END AS rapporto_copertura,
    CASE
        WHEN c.copertura_target > 0 AND mc.copertura_attuale IS NOT NULL
        THEN round(1.00 - least(1.00, mc.copertura_attuale / c.copertura_target), 4)
        ELSE NULL
    END AS gap_controllo,
    CASE
        WHEN c.copertura_target > 0 AND mc.copertura_attuale IS NOT NULL
        THEN round(least(1.00, mc.copertura_attuale / c.copertura_target) * m.peso, 4)
        ELSE NULL
    END AS contributo_pesato
FROM public.assessment_fncsdp a
JOIN public.profilo_target_fncsdp pt ON pt.id = a.profilo_target_id
JOIN public.organizzazione o ON o.id = pt.organizzazione_id
JOIN public.controllo_target_fncsdp c
  ON c.profilo_target_id = pt.id
 AND c.attiva IS TRUE
JOIN public.controllo_target_subcategory_fncsdp m
  ON m.controllo_target_id = c.id
 AND m.attiva IS TRUE
JOIN public.fncsdp_subcategory s
  ON s.id = m.subcategory_id
 AND s.attiva IS TRUE
LEFT JOIN public.misura_controllo_fncsdp mc
  ON mc.assessment_id = a.id
 AND mc.controllo_target_id = c.id
 AND mc.attiva IS TRUE;

