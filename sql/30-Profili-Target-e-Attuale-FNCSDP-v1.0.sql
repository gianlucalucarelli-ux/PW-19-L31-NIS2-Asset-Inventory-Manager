CREATE OR REPLACE FUNCTION public.fn_completa_assessment_fncsdp(p_assessment_id bigint)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
    v_attesi integer;
    v_misure integer;
    v_incomplete integer;
BEGIN
    IF NOT public.fn_accesso_operativo() THEN
        RAISE EXCEPTION 'Accesso operativo non autorizzato.';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM public.assessment_fncsdp
        WHERE id = p_assessment_id
          AND stato = 'BOZZA'
          AND attiva IS TRUE
    ) THEN
        RAISE EXCEPTION 'Assessment non disponibile oppure gia completato.';
    END IF;

    SELECT count(*)
    INTO v_attesi
    FROM public.assessment_fncsdp a
    JOIN public.controllo_target_fncsdp c
      ON c.profilo_target_id = a.profilo_target_id
     AND c.attiva IS TRUE
    WHERE a.id = p_assessment_id;

    SELECT count(*)
    INTO v_misure
    FROM public.misura_controllo_fncsdp
    WHERE assessment_id = p_assessment_id
      AND attiva IS TRUE;

    IF v_attesi = 0 OR v_misure <> v_attesi THEN
        RAISE EXCEPTION 'Numero misure incoerente: attese %, presenti %.', v_attesi, v_misure;
    END IF;

    SELECT count(*)
    INTO v_incomplete
    FROM public.misura_controllo_fncsdp
    WHERE assessment_id = p_assessment_id
      AND attiva IS TRUE
      AND (
          copertura_attuale IS NULL
          OR (copertura_attuale > 0.00 AND livello_maturita IS NULL)
          OR (copertura_attuale = 0.00 AND livello_maturita IS NOT NULL)
      );

    IF v_incomplete > 0 THEN
        RAISE EXCEPTION '% misure non sono complete o coerenti.', v_incomplete;
    END IF;

    PERFORM set_config('app.fncsdp_assessment_completion', '1', true);

    UPDATE public.assessment_fncsdp
    SET
        stato = 'COMPLETATO',
        completato_da = auth.uid(),
        completato_il = clock_timestamp(),
        aggiornato_il = clock_timestamp()
    WHERE id = p_assessment_id;

    RETURN p_assessment_id;
END;
$$;

