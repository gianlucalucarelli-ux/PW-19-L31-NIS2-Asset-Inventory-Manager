DO $$
DECLARE
    v_tabelle integer;
    v_viste integer;
    v_subcategory integer;
    v_rls integer;
    v_security_invoker integer;
    v_trigger_audit integer;
    v_trigger_delete integer;
BEGIN
    SELECT count(*) INTO v_tabelle
    FROM information_schema.tables
    WHERE table_schema = 'public'
      AND table_type = 'BASE TABLE';

    SELECT count(*) INTO v_viste
    FROM information_schema.views
    WHERE table_schema = 'public';

    SELECT count(*) INTO v_subcategory
    FROM public.fncsdp_subcategory
    WHERE versione_framework = '2.0'
      AND codice IN ('ID.AM-1', 'ID.AM-2', 'ID.AM-3', 'ID.AM-4', 'ID.AM-5', 'ID.AM-6')
      AND attiva IS TRUE;

    SELECT count(*) INTO v_rls
    FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relname IN (
          'fncsdp_subcategory',
          'profilo_target_fncsdp',
          'controllo_target_fncsdp',
          'controllo_target_subcategory_fncsdp',
          'assessment_fncsdp',
          'misura_controllo_fncsdp'
      )
      AND c.relrowsecurity IS TRUE;

    SELECT count(*) INTO v_security_invoker
    FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relname IN (
          'vista_profili_target_fncsdp',
          'vista_controlli_target_fncsdp',
          'vista_profili_attuali_fncsdp',
          'vista_valutazione_fncsdp'
      )
      AND 'security_invoker=true' = ANY(coalesce(c.reloptions, ARRAY[]::text[]));

    SELECT count(*) INTO v_trigger_audit
    FROM pg_catalog.pg_trigger t
    JOIN pg_catalog.pg_class c ON c.oid = t.tgrelid
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relname IN (
          'fncsdp_subcategory',
          'profilo_target_fncsdp',
          'controllo_target_fncsdp',
          'controllo_target_subcategory_fncsdp',
          'assessment_fncsdp',
          'misura_controllo_fncsdp'
      )
      AND t.tgname = 'trg_audit_' || c.relname
      AND NOT t.tgisinternal;

    SELECT count(*) INTO v_trigger_delete
    FROM pg_catalog.pg_trigger t
    JOIN pg_catalog.pg_class c ON c.oid = t.tgrelid
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relname IN (
          'fncsdp_subcategory',
          'profilo_target_fncsdp',
          'controllo_target_fncsdp',
          'controllo_target_subcategory_fncsdp',
          'assessment_fncsdp',
          'misura_controllo_fncsdp'
      )
      AND t.tgname = 'trg_blocca_delete_' || c.relname
      AND NOT t.tgisinternal;

    IF v_tabelle <> 36 THEN
        RAISE EXCEPTION 'Conteggio finale tabelle inatteso: % invece di 36.', v_tabelle;
    END IF;

    IF v_viste <> 11 THEN
        RAISE EXCEPTION 'Conteggio finale viste inatteso: % invece di 11.', v_viste;
    END IF;

    IF v_subcategory <> 6 THEN
        RAISE EXCEPTION 'Catalogo ID.AM incompleto: % righe invece di 6.', v_subcategory;
    END IF;

    IF v_rls <> 6 THEN
        RAISE EXCEPTION 'RLS non attiva su tutte le sei tabelle FNCSDP.';
    END IF;

    IF v_security_invoker <> 4 THEN
        RAISE EXCEPTION 'Una o piu viste FNCSDP non sono security_invoker.';
    END IF;

    IF v_trigger_audit <> 6 OR v_trigger_delete <> 6 THEN
        RAISE EXCEPTION 'Trigger FNCSDP incompleti: audit %, blocco DELETE %.', v_trigger_audit, v_trigger_delete;
    END IF;
END;
$$;

