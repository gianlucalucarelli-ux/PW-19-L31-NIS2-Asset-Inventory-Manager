CREATE OR REPLACE FUNCTION public.fn_audit_fncsdp()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
    v_old jsonb;
    v_new jsonb;
    v_riga jsonb;
    v_record_id text;
    v_codice text;
    v_nome text;
    v_utente_id uuid;
    v_utente_email text;
    v_aal text;
    v_ruolo_jwt text;
    v_ruolo_database text;
    v_origine text;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        v_old := to_jsonb(OLD);
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        v_new := to_jsonb(NEW);
    END IF;

    IF TG_OP = 'UPDATE' AND v_old IS NOT DISTINCT FROM v_new THEN
        RETURN NEW;
    END IF;

    v_riga := coalesce(v_new, v_old, '{}'::jsonb);
    v_record_id := coalesce(nullif(v_riga ->> 'id', ''), md5(v_riga::text));
    v_codice := coalesce(nullif(v_riga ->> 'codice', ''), nullif(v_riga ->> 'codice_record', ''));
    v_nome := left(coalesce(nullif(v_riga ->> 'nome', ''), nullif(v_riga ->> 'descrizione', ''), TG_TABLE_NAME), 500);

    v_utente_id := auth.uid();
    v_utente_email := nullif(auth.jwt() ->> 'email', '');
    v_aal := nullif(auth.jwt() ->> 'aal', '');
    v_ruolo_jwt := nullif(auth.jwt() ->> 'role', '');
    v_ruolo_database := session_user;
    v_origine := CASE WHEN v_utente_id IS NOT NULL OR v_utente_email IS NOT NULL THEN 'JWT' ELSE 'DATABASE' END;

    INSERT INTO public.audit_log (
        asset_id,
        utente,
        operazione,
        data_modifica,
        valore_precedente,
        valore_nuovo,
        tabella,
        tipo_entita,
        record_id,
        chiave_record,
        codice_record,
        nome_record,
        servizio_id,
        fornitore_id,
        utente_id,
        utente_email,
        livello_autenticazione,
        ruolo_jwt,
        ruolo_database,
        origine_utente,
        valore_precedente_jsonb,
        valore_nuovo_jsonb
    )
    VALUES (
        NULL,
        coalesce(v_utente_email, v_utente_id::text, v_ruolo_database, 'UTENTE_NON_IDENTIFICATO'),
        TG_OP,
        timezone('UTC', clock_timestamp()),
        CASE WHEN v_old IS NULL THEN NULL ELSE v_old::text END,
        CASE WHEN v_new IS NULL THEN NULL ELSE v_new::text END,
        TG_TABLE_NAME,
        CASE WHEN TG_TABLE_NAME = 'controllo_target_subcategory_fncsdp' THEN 'RELAZIONE' ELSE 'ENTITA' END,
        v_record_id,
        jsonb_strip_nulls(jsonb_build_object(
            'id', v_riga -> 'id',
            'profilo_target_id', v_riga -> 'profilo_target_id',
            'controllo_target_id', v_riga -> 'controllo_target_id',
            'subcategory_id', v_riga -> 'subcategory_id',
            'assessment_id', v_riga -> 'assessment_id'
        )),
        v_codice,
        v_nome,
        NULL,
        NULL,
        v_utente_id,
        v_utente_email,
        v_aal,
        v_ruolo_jwt,
        v_ruolo_database,
        v_origine,
        v_old,
        v_new
    );

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

