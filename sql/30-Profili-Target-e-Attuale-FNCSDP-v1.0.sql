DO $$
DECLARE
    v_tabella text;
    v_sequenza text;
BEGIN
    FOREACH v_tabella IN ARRAY ARRAY[
        'fncsdp_subcategory',
        'profilo_target_fncsdp',
        'controllo_target_fncsdp',
        'controllo_target_subcategory_fncsdp',
        'assessment_fncsdp',
        'misura_controllo_fncsdp'
    ]
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', v_tabella);
        EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.%I FROM anon', v_tabella);
        EXECUTE format('REVOKE DELETE, TRUNCATE ON TABLE public.%I FROM authenticated', v_tabella);
        EXECUTE format('DROP POLICY IF EXISTS "Read_Operativo_Policy" ON public.%I', v_tabella);
        EXECUTE format(
            'CREATE POLICY "Read_Operativo_Policy" ON public.%I
             AS PERMISSIVE FOR SELECT TO authenticated
             USING (public.fn_accesso_operativo())',
            v_tabella
        );

        v_sequenza := pg_get_serial_sequence(format('public.%I', v_tabella), 'id');
        IF v_sequenza IS NOT NULL THEN
            EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO authenticated', v_sequenza);
            EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM anon', v_sequenza);
        END IF;
    END LOOP;
END;
$$;

