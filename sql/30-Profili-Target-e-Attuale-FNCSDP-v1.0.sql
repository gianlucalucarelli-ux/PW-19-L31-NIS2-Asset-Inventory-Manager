CREATE OR REPLACE FUNCTION public.fn_valida_mapping_fncsdp()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_stato_nuovo text;
    v_stato_precedente text;
BEGIN
    SELECT pt.stato
    INTO v_stato_nuovo
    FROM public.controllo_target_fncsdp c
    JOIN public.profilo_target_fncsdp pt ON pt.id = c.profilo_target_id
    WHERE c.id = NEW.controllo_target_id;

    IF TG_OP = 'UPDATE' THEN
        SELECT pt.stato
        INTO v_stato_precedente
        FROM public.controllo_target_fncsdp c
        JOIN public.profilo_target_fncsdp pt ON pt.id = c.profilo_target_id
        WHERE c.id = OLD.controllo_target_id;
    END IF;

    IF v_stato_nuovo IS NULL THEN
        RAISE EXCEPTION 'Controllo Target non valido.';
    END IF;

    IF v_stato_nuovo = 'APPROVATO' OR v_stato_precedente = 'APPROVATO' THEN
        RAISE EXCEPTION 'Il Profilo Target approvato non puo essere modificato.';
    END IF;

    RETURN NEW;
END;
$$;

ALTER FUNCTION public.fn_valida_mapping_fncsdp() OWNER TO postgres;
REVOKE ALL ON FUNCTION public.fn_valida_mapping_fncsdp() FROM PUBLIC, anon, authenticated;

