CREATE OR REPLACE FUNCTION public.fn_valida_profilo_target_fncsdp()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    IF TG_OP = 'INSERT'
       AND NEW.stato <> 'BOZZA'
       AND coalesce(current_setting('app.fncsdp_target_approval', true), '0') <> '1' THEN
        RAISE EXCEPTION 'Un Profilo Target deve essere creato nello stato BOZZA.';
    END IF;

    IF TG_OP = 'UPDATE' AND OLD.stato = 'APPROVATO' THEN
        IF ROW(
            NEW.organizzazione_id,
            NEW.codice,
            NEW.nome,
            NEW.descrizione,
            NEW.perimetro,
            NEW.versione,
            NEW.stato,
            NEW.approvato_da,
            NEW.approvato_il
        ) IS DISTINCT FROM ROW(
            OLD.organizzazione_id,
            OLD.codice,
            OLD.nome,
            OLD.descrizione,
            OLD.perimetro,
            OLD.versione,
            OLD.stato,
            OLD.approvato_da,
            OLD.approvato_il
        ) THEN
            RAISE EXCEPTION 'Il Profilo Target approvato e immutabile.';
        END IF;
    END IF;

    IF TG_OP = 'UPDATE'
       AND OLD.stato = 'BOZZA'
       AND NEW.stato = 'APPROVATO'
       AND coalesce(current_setting('app.fncsdp_target_approval', true), '0') <> '1' THEN
        RAISE EXCEPTION 'Usare la funzione fn_approva_profilo_target_fncsdp().';
    END IF;

    NEW.aggiornato_il := clock_timestamp();
    RETURN NEW;
END;
$$;

ALTER FUNCTION public.fn_valida_profilo_target_fncsdp() OWNER TO postgres;
REVOKE ALL ON FUNCTION public.fn_valida_profilo_target_fncsdp() FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.fn_valida_assessment_fncsdp()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_stato_target text;
BEGIN
    SELECT stato
    INTO v_stato_target
    FROM public.profilo_target_fncsdp
    WHERE id = NEW.profilo_target_id
      AND attiva IS TRUE;

    IF v_stato_target IS DISTINCT FROM 'APPROVATO' THEN
        RAISE EXCEPTION 'L''assessment richiede un Profilo Target attivo e approvato.';
    END IF;

    IF NEW.responsabile_assessor_id IS NOT NULL
       AND NOT EXISTS (
           SELECT 1
           FROM public.responsabile r
           JOIN public.profilo_target_fncsdp pt
             ON pt.id = NEW.profilo_target_id
            AND pt.organizzazione_id = r.organizzazione_id
           WHERE r.id = NEW.responsabile_assessor_id
             AND r.attiva IS TRUE
       ) THEN
        RAISE EXCEPTION 'Assessor non valido, non attivo o appartenente a un altro soggetto NIS2.';
    END IF;

    IF TG_OP = 'UPDATE' AND NEW.profilo_target_id IS DISTINCT FROM OLD.profilo_target_id THEN
        RAISE EXCEPTION 'Il Profilo Target di un assessment non puo essere modificato.';
    END IF;

    IF TG_OP = 'INSERT'
       AND NEW.stato <> 'BOZZA'
       AND coalesce(current_setting('app.fncsdp_assessment_completion', true), '0') <> '1' THEN
        RAISE EXCEPTION 'Un assessment deve essere creato nello stato BOZZA.';
    END IF;

    IF TG_OP = 'UPDATE' AND OLD.stato = 'COMPLETATO' THEN
        IF ROW(
            NEW.profilo_target_id,
            NEW.codice,
            NEW.nome,
            NEW.data_assessment,
            NEW.responsabile_assessor_id,
            NEW.note,
            NEW.stato,
            NEW.completato_da,
            NEW.completato_il
        ) IS DISTINCT FROM ROW(
            OLD.profilo_target_id,
            OLD.codice,
            OLD.nome,
            OLD.data_assessment,
            OLD.responsabile_assessor_id,
            OLD.note,
            OLD.stato,
            OLD.completato_da,
            OLD.completato_il
        ) THEN
            RAISE EXCEPTION 'L''assessment completato e immutabile.';
        END IF;
    END IF;

    IF TG_OP = 'UPDATE'
       AND OLD.stato = 'BOZZA'
       AND NEW.stato = 'COMPLETATO'
       AND coalesce(current_setting('app.fncsdp_assessment_completion', true), '0') <> '1' THEN
        RAISE EXCEPTION 'Usare la funzione fn_completa_assessment_fncsdp().';
    END IF;

    NEW.aggiornato_il := clock_timestamp();
    RETURN NEW;
END;
$$;

