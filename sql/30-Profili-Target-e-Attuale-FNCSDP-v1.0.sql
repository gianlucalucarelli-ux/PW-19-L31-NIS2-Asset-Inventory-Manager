    p_codice text,
    p_nome text,
    p_descrizione text,
    p_perimetro text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
    v_profilo_id bigint;
    v_subcategory record;
    v_controllo_id bigint;
    v_codice text;
    v_nome text;
    v_descrizione text;
BEGIN
    IF NOT public.fn_accesso_operativo() THEN
        RAISE EXCEPTION 'Accesso operativo non autorizzato.';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM public.organizzazione
        WHERE id = p_organizzazione_id
          AND attiva IS TRUE
    ) THEN
        RAISE EXCEPTION 'Soggetto NIS2 non valido o non attivo.';
    END IF;

    v_codice := upper(btrim(coalesce(p_codice, '')));
    v_nome := btrim(coalesce(p_nome, ''));
    v_descrizione := nullif(btrim(coalesce(p_descrizione, '')), '');

    IF v_codice !~ '^[A-Z0-9][A-Z0-9_-]{2,39}$' THEN
        RAISE EXCEPTION 'Codice Profilo Target non valido.';
    END IF;

    IF length(v_nome) < 3 THEN
        RAISE EXCEPTION 'Nome Profilo Target obbligatorio.';
    END IF;

    IF length(btrim(coalesce(p_perimetro, ''))) < 10 THEN
        RAISE EXCEPTION 'Descrivere il perimetro del Profilo Target con almeno 10 caratteri.';
    END IF;

    INSERT INTO public.profilo_target_fncsdp (
        organizzazione_id,
        codice,
        nome,
        descrizione,
        perimetro,
        creato_da
    )
    VALUES (
        p_organizzazione_id,
        v_codice,
        v_nome,
        v_descrizione,
        btrim(p_perimetro),
        auth.uid()
    )
    RETURNING id INTO v_profilo_id;

    FOR v_subcategory IN
        SELECT id, codice, descrizione, ordine
        FROM public.fncsdp_subcategory
        WHERE versione_framework = '2.0'
          AND codice BETWEEN 'ID.AM-1' AND 'ID.AM-6'
          AND attiva IS TRUE
        ORDER BY ordine
    LOOP
        INSERT INTO public.controllo_target_fncsdp (
            profilo_target_id,
            codice,
            nome,
            descrizione,
            copertura_target,
            ordine
        )
        VALUES (
            v_profilo_id,
            'CTRL-' || replace(v_subcategory.codice, '.', '-'),
            CASE v_subcategory.codice
                WHEN 'ID.AM-1' THEN 'Inventario dei sistemi e apparati fisici'
                WHEN 'ID.AM-2' THEN 'Inventario delle piattaforme e applicazioni software'
                WHEN 'ID.AM-3' THEN 'Mappatura dei flussi di dati e comunicazioni'
                WHEN 'ID.AM-4' THEN 'Catalogo dei sistemi informativi esterni'
                WHEN 'ID.AM-5' THEN 'Classificazione e prioritizzazione delle risorse'
                WHEN 'ID.AM-6' THEN 'Assegnazione di ruoli e responsabilita cybersecurity'
            END,
            CASE v_subcategory.codice
                WHEN 'ID.AM-1' THEN 'Mantenere aggiornato il censimento dei sistemi e degli apparati fisici compresi nel perimetro.'
                WHEN 'ID.AM-2' THEN 'Mantenere aggiornato il censimento delle piattaforme e delle applicazioni software comprese nel perimetro.'
                WHEN 'ID.AM-3' THEN 'Identificare e documentare i principali flussi di dati e comunicazioni associati ai servizi e agli asset censiti.'
                WHEN 'ID.AM-4' THEN 'Catalogare i sistemi informativi esterni e le dipendenze da fornitori o servizi terzi rilevanti.'
                WHEN 'ID.AM-5' THEN 'Classificare e prioritizzare le risorse secondo criticita, valore e contributo ai servizi del soggetto NIS2.'
                WHEN 'ID.AM-6' THEN 'Definire e mantenere tracciati ruoli, responsabilita e incarichi cybersecurity interni ed esterni.'
            END,
            1.00,
            v_subcategory.ordine
        )
        RETURNING id INTO v_controllo_id;

        INSERT INTO public.controllo_target_subcategory_fncsdp (
            controllo_target_id,
            subcategory_id,
            peso
        )
        VALUES (
            v_controllo_id,
            v_subcategory.id,
            1.000
        );
    END LOOP;

    RETURN v_profilo_id;
END;
$$;

