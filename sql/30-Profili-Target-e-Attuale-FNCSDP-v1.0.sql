--
-- PRINCIPI APPLICATI:
--   1. nessuna duplicazione dell'organizzazione nell'assessment;
--   2. nessuna memorizzazione di score o gap: sono calcolati nelle viste;
--   3. relazione molti-a-molti controllo/subcategory normalizzata;
--   4. Profilo Attuale ottenuto da assessment + misure dei controlli;
--   5. stesso insieme di controlli e mapping del Profilo Target;
--   6. copertura su scala 0, 0.2, 0.4, 0.6, 0.8, 1;
--   7. maturita CMMI da 1 a 5, non applicabile con copertura nulla;
--   8. RLS, audit, archiviazione logica e blocco DELETE coerenti col progetto.
-- =========================================================================

BEGIN;

-- =========================================================================
-- 1. VERIFICHE PRELIMINARI BLOCCANTI
-- =========================================================================

DO $$
DECLARE
    v_tabelle integer;
    v_viste integer;
BEGIN
    SELECT count(*) INTO v_tabelle
    FROM information_schema.tables
    WHERE table_schema = 'public'
      AND table_type = 'BASE TABLE';

    SELECT count(*) INTO v_viste
    FROM information_schema.views
    WHERE table_schema = 'public';

    IF v_tabelle <> 30 THEN
        RAISE EXCEPTION 'Numero tabelle public inatteso: % invece di 30.', v_tabelle;
    END IF;

    IF v_viste <> 7 THEN
        RAISE EXCEPTION 'Numero viste public inatteso: % invece di 7.', v_viste;
    END IF;

    IF to_regclass('public.organizzazione') IS NULL
       OR to_regclass('public.responsabile') IS NULL
       OR to_regclass('public.audit_log') IS NULL THEN
        RAISE EXCEPTION 'Prerequisiti mancanti: organizzazione, responsabile o audit_log.';
    END IF;

    IF to_regprocedure('public.fn_accesso_operativo()') IS NULL
       OR to_regprocedure('public.fn_gestisci_archiviazione_logica()') IS NULL
       OR to_regprocedure('public.fn_blocca_cancellazione_fisica()') IS NULL THEN
        RAISE EXCEPTION 'Prerequisiti mancanti: funzioni di accesso, archiviazione o blocco DELETE.';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM pg_catalog.pg_class c
        JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public'
          AND c.relname IN (
              'fncsdp_subcategory',
              'profilo_target_fncsdp',
              'controllo_target_fncsdp',
              'controllo_target_subcategory_fncsdp',
              'assessment_fncsdp',
              'misura_controllo_fncsdp'
          )
    ) THEN
        RAISE EXCEPTION 'Sono gia presenti oggetti FNCSDP: interrompere e verificare lo stato del database.';
    END IF;
END;
$$;

-- =========================================================================
-- 2. CATALOGO DELLE SUBCATEGORY FNCSDP
--
-- Function e Category non vengono duplicate: sono ricavabili dal codice
-- canonico della Subcategory (es. ID.AM-1 -> Function ID, Category ID.AM).
-- =========================================================================

CREATE TABLE public.fncsdp_subcategory (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versione_framework varchar(10) NOT NULL DEFAULT '2.0',
    codice varchar(20) NOT NULL,
    descrizione text NOT NULL,
    ordine integer NOT NULL,
    attiva boolean NOT NULL DEFAULT true,
    archiviato_da uuid,
    archiviato_il timestamptz,
    motivo_archiviazione text,
    creato_il timestamptz NOT NULL DEFAULT clock_timestamp(),
    aggiornato_il timestamptz NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT uq_fncsdp_subcategory_versione_codice
        UNIQUE (versione_framework, codice),

    CONSTRAINT ck_fncsdp_subcategory_codice
        CHECK (codice ~ '^[A-Z]{2}(\.[A-Z]{2,3})?-[0-9]+$'),

    CONSTRAINT ck_fncsdp_subcategory_ordine
        CHECK (ordine > 0),

    CONSTRAINT ck_fncsdp_subcategory_archiviazione
        CHECK (
            (attiva IS TRUE AND archiviato_il IS NULL AND archiviato_da IS NULL AND motivo_archiviazione IS NULL)
            OR
            (attiva IS FALSE AND archiviato_il IS NOT NULL AND motivo_archiviazione IS NOT NULL AND btrim(motivo_archiviazione) <> '')
        )
);

COMMENT ON TABLE public.fncsdp_subcategory IS
    'Catalogo normalizzato delle Subcategory FNCSDP utilizzate dal modulo di assessment.';

