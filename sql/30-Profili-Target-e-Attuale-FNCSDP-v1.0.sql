CREATE OR REPLACE FUNCTION public.fn_valida_misura_controllo_fncsdp()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_target_assessment bigint;
    v_target_controllo bigint;
    v_stato_assessment text;
    v_stato_assessment_precedente text;
BEGIN
    SELECT profilo_target_id, stato
    INTO v_target_assessment, v_stato_assessment
    FROM public.assessment_fncsdp
    WHERE id = NEW.assessment_id
      AND attiva IS TRUE;

    SELECT profilo_target_id
    INTO v_target_controllo
    FROM public.controllo_target_fncsdp
    WHERE id = NEW.controllo_target_id
      AND attiva IS TRUE;

    IF TG_OP = 'UPDATE' THEN
        SELECT stato
        INTO v_stato_assessment_precedente
        FROM public.assessment_fncsdp
        WHERE id = OLD.assessment_id;
    END IF;

    IF v_target_assessment IS NULL OR v_target_controllo IS NULL THEN
        RAISE EXCEPTION 'Assessment o controllo Target non valido.';
    END IF;

    IF TG_OP = 'UPDATE'
       AND (
           NEW.assessment_id IS DISTINCT FROM OLD.assessment_id
           OR NEW.controllo_target_id IS DISTINCT FROM OLD.controllo_target_id
       ) THEN
        RAISE EXCEPTION 'Assessment e controllo della misura non possono essere modificati.';
    END IF;

    IF v_target_assessment <> v_target_controllo THEN
        RAISE EXCEPTION 'Il controllo non appartiene al Profilo Target dell''assessment.';
    END IF;

    IF v_stato_assessment = 'COMPLETATO' OR v_stato_assessment_precedente = 'COMPLETATO' THEN
        RAISE EXCEPTION 'L''assessment completato non puo essere modificato.';
    END IF;

    IF NEW.copertura_attuale = 0.00 THEN
        NEW.livello_maturita := NULL;
    END IF;

    NEW.aggiornato_il := clock_timestamp();
    RETURN NEW;
END;
$$;

